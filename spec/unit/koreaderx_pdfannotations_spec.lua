describe("KOReaderX PDF source import", function()
    local Annotation, util
    setup(function()
        require("commonrequire")
        Annotation = require("document/pdfannotations")
        util = require("util")
    end)
    local function source(number, note)
        return { source = { num = number, gen = 0 }, type = 8,
            boxes = {{ x = 10, y = 10, w = 100, h = 15 }},
            raw = { type = 8, quads = {{10, 10, 109, 10, 10, 24, 109, 24}}, contents = note or "note" } }
    end
    local function build(page, entry)
        return { page = page, drawer = "lighten", text = "selected text", note = entry.raw.contents }
    end
    it("retains local annotations and distinguishes coincident sources", function()
        local old = {{ page = 5, text = "local-only", drawer = "lighten" }}
        local candidate, added, skipped = Annotation.import({[1] = {source(11, "one"), source(12, "two")}}, old, {}, build)
        assert.equals(1, #old)
        assert.equals(3, #candidate)
        assert.equals(2, #added)
        assert.equals(0, skipped)
        local second, newly_added, repeated = Annotation.import({[1] = {source(11, "one"), source(12, "two")}}, candidate, {}, build)
        assert.equals(3, #second)
        assert.equals(0, #newly_added)
        assert.equals(2, repeated)
    end)
    it("deduplicates repeated source IDs within one batch", function()
        local candidate = Annotation.import({[1] = {source(11), source(11)}}, {}, {}, build)
        assert.equals(1, #candidate)
    end)
    it("reconciles a uniquely matching source after xref rewrite", function()
        local old = Annotation.import({[1] = {source(11)}}, {}, {}, build)
        old[1].note = "local note"
        local candidate, added, skipped = Annotation.import({[1] = {source(99)}}, old, {}, build)
        assert.equals(1, #candidate)
        assert.equals(0, #added)
        assert.equals(1, skipped)
        assert.equals(99, candidate[1].koreaderx_pdf_source.parts[1].num)
        assert.equals(11, old[1].koreaderx_pdf_source.parts[1].num)
        assert.equals("local note", candidate[1].note)
    end)
    it("keeps an identical new source when the old ID remains present", function()
        local old = Annotation.import({[1] = {source(11)}}, {}, {}, build)
        local candidate, added = Annotation.import({[1] = {source(11), source(12)}}, old, {}, build)
        assert.equals(2, #candidate)
        assert.equals(1, #added)
    end)
    it("preserves identical direct-object multiplicity", function()
        local annotations = {[1] = {source(0), source(0)}}
        local candidate = Annotation.import(annotations, {}, {}, build)
        assert.equals(2, #candidate)
        local again, added, skipped = Annotation.import(annotations, candidate, {}, build)
        assert.equals(2, #again)
        assert.equals(0, #added)
        assert.equals(2, skipped)
    end)
    it("reports external source edits without overwriting local notes", function()
        local candidate = Annotation.import({[1] = {source(11)}}, {}, {}, build)
        candidate[1].note = "local override"
        local again, added, skipped, invalid, conflicts = Annotation.import({[1] = {source(11, "external")}}, candidate, {}, build)
        assert.equals("local override", again[1].note)
        assert.equals(0, #added)
        assert.equals(0, skipped)
        assert.equals(0, invalid)
        assert.equals(1, conflicts)
    end)
    it("does not resurrect an unchanged locally deleted source", function()
        local entry = source(11)
        local tombstone = Annotation.part(1, entry)
        local candidate, added, skipped = Annotation.import({[1] = {entry}}, {}, {tombstone}, build)
        assert.equals(0, #candidate)
        assert.equals(0, #added)
        assert.equals(1, skipped)
    end)
    it("rejects malformed boxes before invoking text extraction", function()
        local bad = source(11)
        bad.boxes = {}
        local called = false
        local candidate, added, skipped, invalid = Annotation.import({[1] = {bad}}, {}, {}, function() called = true end)
        assert.is_false(called)
        assert.equals(0, #candidate)
        assert.equals(0, #added)
        assert.equals(0, skipped)
        assert.equals(1, invalid)
    end)
    it("does not change original data when an extraction fails mid-batch", function()
        local old = {{ page = 5, text = "keep" }}
        local snapshot = util.tableDeepCopy(old)
        local ok = pcall(Annotation.import, {[1] = {source(11), source(12)}}, old, {}, function(page, entry)
            if entry.source.num == 12 then error("injected extraction failure") end
            return build(page, entry)
        end)
        assert.is_false(ok)
        assert.same(snapshot, old)
    end)
    it("maps all target palette colors and preserves exact raw color separately", function()
        local palette = require("ffi/blitbuffer").HIGHLIGHT_COLORS
        for name, hex in pairs(palette) do
            local r, g, b = hex:match("#(..)(..)(..)")
            assert.equals(name, Annotation.nearestColor({tonumber(r, 16)/255, tonumber(g, 16)/255, tonumber(b, 16)/255}, palette))
        end
    end)
end)

describe("KOReaderX annotation transaction recovery", function()
    local Transaction, ffiUtil, directory
    setup(function()
        require("commonrequire")
        Transaction = require("document/pdfannotationtransaction")
        ffiUtil = require("ffi/util")
    end)
    before_each(function()
        directory = os.tmpname()
        os.remove(directory)
        require("util").makePath(directory)
    end)
    after_each(function() require("ffi/util").purgeDir(directory) end)
    local function pair()
        local pdf = directory .. "/book.pdf"
        local staged = directory .. "/candidate.pdf"
        Transaction.write(pdf, "old PDF bytes")
        Transaction.write(staged, "new PDF bytes")
        local settings = { source_candidate = directory .. "/metadata.lua" }
        Transaction.writeTable(settings.source_candidate, { annotations = { "old" } })
        local metadata = Transaction.stageMetadata(settings, { annotations = { "new" } }, "test")
        return pdf, staged, metadata, Transaction.hash(pdf)
    end
    it("commits and verifies both files with retained backups", function()
        local pdf, staged, metadata, before = pair()
        Transaction.commitPair(pdf, staged, metadata, "test", before)
        assert.equals(metadata.after, Transaction.hash(metadata.path))
        assert.equals(before, Transaction.hash(pdf .. ".koreaderx-test.backup"))
        assert.is_false(Transaction.recover(pdf))
        assert.equals("new", Transaction.readTable(metadata.path).annotations[1])
    end)
    it("finishes the verified pair after failure between renames", function()
        local pdf, staged, metadata, before = pair()
        local real_rename = os.rename
        local rename_stub = stub(os, "rename", function(from, to)
            if to == metadata.path then return nil, "injected metadata rename failure" end
            return real_rename(from, to)
        end)
        local ok = pcall(Transaction.commitPair, pdf, staged, metadata, "test", before)
        rename_stub:revert()
        assert.is_false(ok)
        assert.equals(metadata.before, Transaction.hash(metadata.path))
        assert.is_true(Transaction.recover(pdf))
        assert.equals(metadata.after, Transaction.hash(metadata.path))
        assert.is_false(Transaction.recover(pdf))
    end)
    it("refuses to overwrite external edits before commit", function()
        local pdf, staged, metadata, before = pair()
        Transaction.write(pdf, "external edit")
        local external_hash = Transaction.hash(pdf)
        assert.has_error(function() Transaction.commitPair(pdf, staged, metadata, "test", before) end)
        assert.equals(external_hash, Transaction.hash(pdf))
        assert.equals(metadata.before, Transaction.hash(metadata.path))
    end)
    it("retains originals if fsync fails during staging", function()
        local pdf, _, metadata = pair()
        local original = Transaction.hash(pdf)
        local real_sync = ffiUtil.fsyncOpenedFile
        ffiUtil.fsyncOpenedFile = function() return false, "injected storage failure" end
        local ok = pcall(Transaction.writeTable, metadata.staged, { annotations = {} })
        ffiUtil.fsyncOpenedFile = real_sync
        assert.is_false(ok)
        assert.equals(original, Transaction.hash(pdf))
        assert.equals(metadata.before, Transaction.hash(metadata.path))
    end)
end)
